CREATE TABLE PILOTO
(
    ID   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL
);

CREATE TABLE AERONAVE
(
    PREFIXO                             VARCHAR(255) PRIMARY KEY,
    CATEGORIA                           VARCHAR(31)  NOT NULL,
    VELOCIDADE_DE_CRUZEIRO              INTEGER      NOT NULL,
    AUTONOMIA                           INTEGER      NOT NULL,
    EMPRESA_RESPONSAVEL_PELA_MANUTENCAO VARCHAR(255),
    COMPANHIA_AEREA                     VARCHAR(255),
    CAPACIDADE_MAX_PASSAGEIRO           INTEGER,
    CAPACIDADE_MAX_CARGA_TN             DOUBLE PRECISION,
    CHECK (CATEGORIA IN ('PARTICULAR', 'COMERCIAL_DE_PASSAGEIRO', 'COMERCIAL_DE_CARGA'))
);
