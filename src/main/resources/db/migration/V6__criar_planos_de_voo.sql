CREATE TABLE PLANO_DE_VOO
(
    ID                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STATUS            VARCHAR(255) NOT NULL,
    DATA_HORA_PARTIDA TIMESTAMP    NOT NULL,
    AERONAVE_PREFIXO  VARCHAR(255) NOT NULL REFERENCES AERONAVE (PREFIXO),
    PILOTO_ID         INTEGER      NOT NULL REFERENCES PILOTO (ID),
    CODIGO_ORIGEM     VARCHAR(3)   NOT NULL REFERENCES AEROPORTO (CODIGO),
    CODIGO_DESTINO    VARCHAR(3)   NOT NULL REFERENCES AEROPORTO (CODIGO),
    CHECK (STATUS IN ('EDICAO', 'APROVADO', 'CANCELADO', 'ABANDONADO'))
);

CREATE TABLE TRECHO
(
    ID                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLANO_ID                   INTEGER      NOT NULL REFERENCES PLANO_DE_VOO (ID),
    ORDEM                      INTEGER,
    AEROVIA_ID                 VARCHAR(255) NOT NULL REFERENCES AEROVIA (ID),
    ALTITUDE                   INTEGER      NOT NULL,
    HORARIO_ENTRADA_NA_AEROVIA TIMESTAMP    NOT NULL,
    ACAO_NA_CHEGADA            VARCHAR(255) NOT NULL,
    NUMERO_VAGA_PRETENDIDA     INTEGER,
    TEMPO_PERMANENCIA_MINUTOS  INTEGER,
    CHECK (ACAO_NA_CHEGADA IN ('POUSO', 'SOBREVOO'))
);
