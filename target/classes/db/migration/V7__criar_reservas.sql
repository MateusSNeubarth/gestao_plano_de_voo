CREATE TABLE RESERVA
(
    ID               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO             VARCHAR(31)  NOT NULL,
    PLANO_ID         INTEGER      NOT NULL REFERENCES PLANO_DE_VOO (ID),
    SLOT             TIMESTAMP    NOT NULL,
    AEROVIA_ID       VARCHAR(255) REFERENCES AEROVIA (ID),
    ALTITUDE         INTEGER,
    CODIGO_AEROPORTO VARCHAR(3) REFERENCES AEROPORTO (CODIGO),
    NUMERO_VAGA      INTEGER,
    UNIQUE (AEROVIA_ID, ALTITUDE, SLOT),
    UNIQUE (CODIGO_AEROPORTO, NUMERO_VAGA, SLOT),
    CHECK (TIPO IN ('AEROVIA', 'ESTACIONAMENTO')),
    CHECK (EXTRACT(MINUTE FROM SLOT) = 0 AND EXTRACT(SECOND FROM SLOT) = 0),
    CHECK (TIPO <> 'AEROVIA' OR (AEROVIA_ID IS NOT NULL AND ALTITUDE IS NOT NULL)),
    CHECK (TIPO <> 'ESTACIONAMENTO' OR (CODIGO_AEROPORTO IS NOT NULL AND NUMERO_VAGA IS NOT NULL))
);
